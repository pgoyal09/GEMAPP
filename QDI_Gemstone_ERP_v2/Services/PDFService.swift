                        <th style="text-align:right">Amount</th>
                    </tr>
                </thead>
                <tbody>
                    \(rows)
                </tbody>
            </table>

            <div class="totals-wrapper">
                <table class="totals-table">
                    <tr><td class="label">Subtotal</td><td class="num">\(subtotal.asCurrency)</td></tr>
                    \(taxRow)
                    <tr class="grand"><td class="label">Total</td><td class="num">\(grandTotal.asCurrency)</td></tr>
                </table>
            </div>

            \(notesBlock)

            <div class="footer">
                \(escape(displayCompanyName)) &middot; Thank you for your business
            </div>

            <script>
                // Page numbers via JavaScript (for WKWebView rendering)
                (function() {
                    var footer = document.querySelector('.footer');
                    if (footer) footer.innerHTML += '';
                })();
            </script>
        </body>
        </html>
        """
    }

    private func escape(_ s: String) -> String {
        s
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }

    private func formatAddress(_ customer: Customer?) -> String {
        guard let c = customer else { return "" }
        var parts: [String] = []
        let name = c.displayName
        if !name.isEmpty { parts.append(name) }
        if !c.company.isEmpty { parts.append(c.company) }
        if !c.address.isEmpty { parts.append(c.address) }
        let cityZip = [c.city, c.zip].filter { !$0.isEmpty }
        if !cityZip.isEmpty { parts.append(cityZip.joined(separator: " ")) }
        if !c.country.isEmpty { parts.append(c.country) }
        return parts.joined(separator: "<br/>")
    }

    private func invoiceMetaLines(_ invoice: Invoice) -> [String] {
        var lines: [String] = []
        if !invoice.referenceNumber.isEmpty { lines.append("Invoice #\(invoice.referenceNumber)") }
        lines.append("Date: \(formatDate(invoice.invoiceDate))")
        if let due = invoice.dueDate { lines.append("Due: \(formatDate(due))") }
        if !invoice.terms.isEmpty { lines.append("Terms: \(invoice.terms)") }
        return lines
    }

    private func memoMetaLines(_ memo: Memo) -> [String] {
        var lines: [String] = []
        if !memo.referenceNumber.isEmpty { lines.append("Memo #\(memo.referenceNumber)") }
        if let date = memo.dateAssigned { lines.append("Date: \(formatDate(date))") }
        lines.append("Status: \(memo.status.rawValue)")
        return lines
    }

    private func formatDate(_ date: Date) -> String {
        mediumDateFormatter.string(from: date)
    }

    private func invoiceSubtotal(_ invoice: Invoice) -> Decimal {
        invoice.lineItems.reduce(0) { $0 + $1.amount }
    }

    private func invoiceTotal(_ invoice: Invoice) -> Decimal {
        invoiceSubtotal(invoice)
    }

    private func memoSubtotal(_ memo: Memo) -> Decimal {
        memo.lineItems.reduce(0) { $0 + $1.amount }
    }

    private func memoTotal(_ memo: Memo) -> Decimal {
        memoSubtotal(memo)
    }

    // MARK: - Render HTML to PDF

    private func renderHTMLToPDF(html: String, completion: @escaping @Sendable (Result<URL, Error>) -> Void) {
        let runner = PDFWebViewRunner(
            html: html,
            pageSize: CGSize(width: letterWidth, height: letterHeight)
        ) { result in
            completion(result)
        }
        runner.run()
    }
}

// MARK: - WKWebView PDF runner (must run on main, retains itself until done)

private final class PDFWebViewRunner: NSObject, WKNavigationDelegate {
    let html: String
    let pageSize: CGSize
    let completion: (Result<URL, Error>) -> Void
    private var webView: WKWebView?
    private var selfRetain: PDFWebViewRunner?
    private var timeoutWorkItem: DispatchWorkItem?
    private var didComplete: Bool = false

    enum PDFError: LocalizedError {
        case timeout
        var errorDescription: String? {
            switch self {
            case .timeout: return "PDF generation timed out after 30 seconds"
            }
        }
    }

    init(html: String, pageSize: CGSize, completion: @escaping @Sendable (Result<URL, Error>) -> Void) {
        self.html = html
        self.pageSize = pageSize
        self.completion = completion
        super.init()
    }

    func run() {
        let config = WKWebViewConfiguration()
        let wv = WKWebView(frame: CGRect(origin: .zero, size: pageSize), configuration: config)
        wv.navigationDelegate = self
        webView = wv
        selfRetain = self
        wv.loadHTMLString(html, baseURL: nil)

        // 30-second timeout
        let timeout = DispatchWorkItem { [weak self] in
            guard let self = self, !self.didComplete else { return }
            self.didComplete = true
            self.webView = nil
            self.selfRetain = nil
            self.completion(.failure(PDFError.timeout))
        }
        timeoutWorkItem = timeout
        DispatchQueue.main.asyncAfter(deadline: .now() + 30, execute: timeout)
    }

    private func finish(with result: Result<URL, Error>) {
        guard !didComplete else { return }
        didComplete = true
        timeoutWorkItem?.cancel()
        webView = nil
        selfRetain = nil
        completion(result)
    }

    func webView(_ webView: WKWebView, didFinish navigation: WKNavigation!) {
        let config = WKPDFConfiguration()
        config.rect = CGRect(origin: .zero, size: pageSize)
        webView.createPDF(configuration: config) { [weak self] result in
            guard let self = self else { return }
            switch result {
            case .success(let data):
                do {
                    let fileName = "document-\(UUID().uuidString).pdf"
                    let url = FileManager.default.temporaryDirectory.appendingPathComponent(fileName)
                    try data.write(to: url)
                    self.finish(with: .success(url))
                } catch {
                    self.finish(with: .failure(error))
                }
            case .failure(let error):
                self.finish(with: .failure(error))
            }
        }
    }

    func webView(_ webView: WKWebView, didFail navigation: WKNavigation!, withError error: Error) {
        finish(with: .failure(error))
    }
}
