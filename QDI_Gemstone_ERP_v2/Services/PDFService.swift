import Foundation
import WebKit
#if canImport(AppKit)
import AppKit
#endif

/// Generates PDFs from Invoice or Memo by rendering HTML via WKWebView.
@MainActor
final class PDFService {

    static let shared = PDFService()

    /// UserDefaults key for stored company logo image data (e.g. from file picker).
    static let companyLogoUserDefaultsKey = "companyLogoImageData"

    /// Company name used in the document header when no custom name is set.
    var companyName: String { "Quality Diajewels Inc." }

    private let letterWidth: CGFloat = 612
    private let letterHeight: CGFloat = 792

    /// Cached DateFormatter for medium-style dates (avoids per-call allocation).
    private let mediumDateFormatter: DateFormatter = {
        let f = DateFormatter()
        f.dateStyle = .medium
        return f
    }()

    private init() {}

    // MARK: - Temp File Cleanup

    /// Removes document-*.pdf files in the temp directory older than 1 hour.
    static func cleanupStaleTempFiles() {
        let tempDir = FileManager.default.temporaryDirectory
        let fm = FileManager.default
        guard let contents = try? fm.contentsOfDirectory(
            at: tempDir, includingPropertiesForKeys: [.creationDateKey], options: .skipsHiddenFiles
        ) else { return }

        let oneHourAgo = Date().addingTimeInterval(-3600)
        for fileURL in contents {
            guard fileURL.lastPathComponent.hasPrefix("document-"),
                  fileURL.pathExtension == "pdf" else { continue }
            if let attrs = try? fm.attributesOfItem(atPath: fileURL.path),
               let creationDate = attrs[.creationDate] as? Date,
               creationDate < oneHourAgo {
                try? fm.removeItem(at: fileURL)
            }
        }
    }

    // MARK: - Public API

    func generatePDF(invoice: Invoice, completion: @escaping @Sendable (Result<URL, Error>) -> Void) {
        Self.cleanupStaleTempFiles()
        let html = buildHTML(
            documentTitle: "INVOICE",
            companyName: companyName,
            customerAddress: formatAddress(invoice.customer),
            metaLines: invoiceMetaLines(invoice),
            lineItems: Array(invoice.lineItems),
            subtotal: invoiceSubtotal(invoice),
            tax: nil,
            grandTotal: invoiceTotal(invoice),
            notes: invoice.notes,
            logoBase64: loadLogoBase64()
        )
        renderHTMLToPDF(html: html, completion: completion)
    }

    func generatePDF(memo: Memo, completion: @escaping @Sendable (Result<URL, Error>) -> Void) {
        Self.cleanupStaleTempFiles()
        let html = buildHTML(
            documentTitle: "MEMO",
            companyName: companyName,
            customerAddress: formatAddress(memo.customer),
            metaLines: memoMetaLines(memo),
            lineItems: Array(memo.lineItems),
            subtotal: memoSubtotal(memo),
            tax: nil,
            grandTotal: memoTotal(memo),
            notes: memo.notes,
            logoBase64: loadLogoBase64()
        )
        renderHTMLToPDF(html: html, completion: completion)
    }

    /// Removes a temporary PDF file previously generated by this service.
    func cleanupTempFile(at url: URL) {
        try? FileManager.default.removeItem(at: url)
    }

    // MARK: - Logo

    private func loadLogoBase64() -> String? {
        guard let data = UserDefaults.standard.data(forKey: Self.companyLogoUserDefaultsKey),
              !data.isEmpty else { return nil }
        return data.base64EncodedString()
    }

    /// Call from UI after user picks a logo image to store it for PDF generation.
    static func saveCompanyLogo(_ imageData: Data) {
        UserDefaults.standard.set(imageData, forKey: companyLogoUserDefaultsKey)
    }

    // MARK: - HTML Template

    private func buildHTML(
        documentTitle: String,
        companyName: String,
        customerAddress: String,
        metaLines: [String],
        lineItems: [LineItem],
        subtotal: Decimal,
        tax: Decimal?,
        grandTotal: Decimal,
        notes: String,
        logoBase64: String?
    ) -> String {
        let logoImg: String
        if let base64 = logoBase64 {
            logoImg = #"<img src="data:image/png;base64,\#(base64)" alt="Logo" class="logo" />"#
        } else {
            logoImg = ""
        }

        let metaBlock = metaLines.map { "<p class=\"meta-line\">\($0)</p>" }.joined(separator: "\n")
        let rows = lineItems.map { item in
            """
            <tr>
                <td>\(escape(item.displaySku))</td>
                <td>\(escape(item.displayName))</td>
                <td class="num">\(escape(item.displayCarats))</td>
                <td class="num">\(escape(item.rate.asCurrency))</td>
                <td class="num">\(escape(item.amount.asCurrency))</td>
            </tr>
            """
        }.joined(separator: "\n")

        let taxRow: String
        if let t = tax, t > 0 {
            taxRow = "<tr><td colspan=\"4\" class=\"label\">Tax</td><td class=\"num\">\(t.asCurrency)</td></tr>"
        } else {
            taxRow = ""
        }

        let notesBlock: String
        if !notes.isEmpty {
            notesBlock = """
            <div class="notes">
                <strong>Notes</strong><br/>
                \(escape(notes))
            </div>
            """
        } else {
            notesBlock = ""
        }

        // Read company info from UserDefaults, falling back to parameter
        let storedCompanyName = UserDefaults.standard.string(forKey: "companyName")
        let displayCompanyName = (storedCompanyName?.isEmpty == false) ? storedCompanyName! : companyName
        let companyAddress = UserDefaults.standard.string(forKey: "companyAddress") ?? ""
        let companyPhone = UserDefaults.standard.string(forKey: "companyPhone") ?? ""
        let companyEmail = UserDefaults.standard.string(forKey: "companyEmail") ?? ""

        var companyInfoLines: [String] = [escape(displayCompanyName)]
        if !companyAddress.isEmpty { companyInfoLines.append(contentsOf: companyAddress.components(separatedBy: "\n").map { escape($0) }) }
        if !companyPhone.isEmpty { companyInfoLines.append(escape(companyPhone)) }
        if !companyEmail.isEmpty { companyInfoLines.append(escape(companyEmail)) }
        let companyBlock = companyInfoLines.joined(separator: "<br/>")

        return """
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="utf-8">
            <style>
                @page {
                    margin: 18mm 15mm 22mm 15mm;
                    @bottom-center {
                        content: counter(page) " of " counter(pages);
                        font-size: 9pt;
                        color: #888;
                    }
                }
