                /* Header */
                .header {
                    display: flex;
                    justify-content: space-between;
                    align-items: flex-start;
                    padding-bottom: 16px;
                    border-bottom: 2px solid #1a1a1a;
                    margin-bottom: 20px;
                }
                .logo { max-height: 60px; max-width: 180px; }
                .company-info {
                    text-align: right;
                    font-size: 9pt;
                    color: #444;
                    line-height: 1.6;
                }
                .company-info strong {
                    font-size: 13pt;
                    color: #1a1a1a;
                    display: block;
                    margin-bottom: 2px;
                }

                /* Document Title */
                .doc-title {
                    font-size: 24pt;
                    font-weight: 700;
                    letter-spacing: 2px;
                    color: #1a1a1a;
                    margin: 20px 0 6px 0;
                    text-transform: uppercase;
                }

                /* Meta & Bill-To Row */
                .info-row {
                    display: flex;
                    justify-content: space-between;
                    margin: 12px 0 24px 0;
                }
                .bill-to, .meta {
                    width: 48%;
                }
                .section-label {
                    font-size: 8pt;
                    text-transform: uppercase;
                    letter-spacing: 1.5px;
                    color: #888;
                    font-weight: 600;
                    margin-bottom: 4px;
                }
                .meta-line {
                    margin: 1px 0;
                    color: #333;
                    font-size: 10pt;
                }

                /* Line Items Table */
                .items-table {
                    width: 100%;
                    border-collapse: collapse;
                    margin: 0 0 16px 0;
                }
                .items-table thead th {
                    background: #f5f5f5;
                    border-bottom: 2px solid #1a1a1a;
                    border-top: 2px solid #1a1a1a;
                    padding: 8px 10px;
                    text-align: left;
                    font-size: 8pt;
                    text-transform: uppercase;
                    letter-spacing: 1px;
                    color: #555;
                    font-weight: 600;
                }
                .items-table thead { display: table-header-group; }
                .items-table tbody tr { page-break-inside: avoid; }
                .items-table tbody tr:nth-child(even) { background: #fafafa; }
                .items-table tbody td {
                    padding: 7px 10px;
                    border-bottom: 1px solid #e5e5e5;
                    font-size: 10pt;
                    vertical-align: top;
                }
                .items-table td.num { text-align: right; font-variant-numeric: tabular-nums; }

                /* Totals */
                .totals-wrapper {
                    display: flex;
                    justify-content: flex-end;
